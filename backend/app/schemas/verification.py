"""
Verification schemas and lifecycle models for Phase 7 Code Verification Ladder.
Defines explicit code lifecycle states, per-rung verification telemetry,
and comprehensive verification reports.
"""

from enum import Enum
from typing import Dict, Any, List, Optional
from pydantic import BaseModel, Field


class CodeLifecycleState(str, Enum):
    """Explicit lifecycle states for synthesized scientific code."""
    GENERATED = "GENERATED"      # Code generated by synthesis engine, pending verification
    VALIDATED = "VALIDATED"      # Passed static ladder (AST, security, imports, bytecode compile)
    EXECUTABLE = "EXECUTABLE"    # Passed runtime instantiation and dummy forward pass
    VERIFIED = "VERIFIED"        # Passed backward pass, optimizer mutation, and tiny training loop
    FAILED = "FAILED"            # Rejected at one or more verification rungs
    NEEDS_REVIEW = "NEEDS_REVIEW"# Requires human attention (exhausted repair budget or invariant mismatch)


class VerificationRung(str, Enum):
    """The 12 distinct rungs of the Code Generation Verification Ladder."""
    AST_VALIDATION = "AST_VALIDATION"
    SECURITY_ANALYSIS = "SECURITY_ANALYSIS"
    IMPORT_VALIDATION = "IMPORT_VALIDATION"
    BYTECODE_COMPILATION = "BYTECODE_COMPILATION"
    OPTIONAL_TYPE_CHECK = "OPTIONAL_TYPE_CHECK"
    MODEL_INITIALIZATION = "MODEL_INITIALIZATION"
    FORWARD_PASS = "FORWARD_PASS"
    LOSS_CALCULATION = "LOSS_CALCULATION"
    BACKWARD_PASS = "BACKWARD_PASS"
    OPTIMIZER_STEP = "OPTIMIZER_STEP"
    TINY_TRAINING_RUN = "TINY_TRAINING_RUN"
    FUNCTIONAL_EVALUATION = "FUNCTIONAL_EVALUATION"


class RungResult(BaseModel):
    """Detailed telemetry and status for an individual ladder rung."""
    rung: VerificationRung
    passed: bool
    duration_ms: float = 0.0
    error: Optional[str] = None
    telemetry: Dict[str, Any] = Field(default_factory=dict)


class CodeVerificationReport(BaseModel):
    """
    Independent, machine-readable report recording verification ladder results.
    Never equates execution success directly with paper correctness.
    """
    candidate_id: str = "candidate_default"
    file_path: str = "model.py"
    lifecycle_state: CodeLifecycleState = CodeLifecycleState.GENERATED
    highest_rung_reached: Optional[VerificationRung] = None
    all_rungs_passed: bool = False
    rungs: List[RungResult] = Field(default_factory=list)
    paper_fidelity_score: float = Field(
        default=0.0,
        description="Fidelity to extracted paper hyperparameters and architectural primitives (0.0 to 100.0)"
    )
    fidelity_breakdown: Dict[str, Any] = Field(default_factory=dict)
    repair_feedback: Optional[str] = Field(
        default=None,
        description="Actionable diagnostic message fed into Reflexion repair loops"
    )

    def get_rung_result(self, rung: VerificationRung) -> Optional[RungResult]:
        for r in self.rungs:
            if r.rung == rung:
                return r
        return None
